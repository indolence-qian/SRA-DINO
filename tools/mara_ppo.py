"""On-policy MARA: a frozen refinement environment, a categorical actor and V(s).

No GT enters observations/actions. PPO reuses STORED observations, never a
trajectory regenerated by a changed network. The legacy gain heads are not V.
"""
from dataclasses import dataclass, replace
import math

import torch
from torch import nn
from torch.distributions import Categorical

from tools.mara_agent import (
    MARAAgent, MARAConfig, _compose_high_res_probability, _masked_mean,
    _resize_map, build_candidate_masks, quality_score,
)
from tools.mara_diagnostics import validate_cache

PROTOCOL = "mara_ppo_v1"
INPUTS = ("base_prob", "base_logits", "layer_maps", "evidence_maps", "global_evidence")
ARMS = {"V": True, "MC": False}


@dataclass
class PPOConfig:
    gamma: float = 1.0
    gae_lambda: float = 1.0
    trajectories: int = 4
    update_epochs: int = 4
    minibatch_size: int = 16
    clip_eps: float = .2
    value_coef: float = .5
    entropy_coef: float = .01
    actor_lr: float = 1e-4
    critic_lr: float = 3e-4
    grad_clip: float = 1.0
    use_value: bool = True

    def __post_init__(self):
        if not 0 < self.gamma <= 1 or not 0 <= self.gae_lambda <= 1:
            raise ValueError("Invalid gamma/lambda")
        if min(self.trajectories, self.update_epochs, self.minibatch_size) < 1:
            raise ValueError("PPO budgets must be positive")
        if not 0 < self.clip_eps < 1 or min(self.actor_lr, self.critic_lr, self.grad_clip) <= 0:
            raise ValueError("Invalid PPO optimizer parameters")
        if min(self.value_coef, self.entropy_coef) < 0:
            raise ValueError("Negative loss coefficient")
        if not all(math.isfinite(v) for v in vars(self).values()):
            raise ValueError("Nonfinite PPO config")


def environment_config(template, steps=3):
    # A new, explicit MDP: HR utility, STOP=0, REFINE cost=.003, no gain veto.
    return replace(template, max_steps=steps, gamma=1., step_cost=.001, refine_cost=.002,
                   reward_cls_weight=.5, reward_loc_weight=1., reward_conf_weight=0., reward_fp_weight=.2,
                   use_gain_gate=False, hard_gain_gate=False, stop_on_gain_reject=False,
                   freeze_noop_state=True, force_first_refine=False, include_base_trajectory=False)


def encoder(channels, hidden):
    return nn.Sequential(nn.Conv2d(channels, hidden, 3, padding=1), nn.GroupNorm(8, hidden), nn.GELU(),
                         nn.Conv2d(hidden, hidden, 3, padding=1), nn.GroupNorm(8, hidden), nn.GELU())


class Actor(nn.Module):
    def __init__(self, cfg):
        super().__init__()
        hidden = cfg.hidden_dim
        self.cfg = cfg
        self.encoder = encoder(7+cfg.num_layers+cfg.evidence_channels, hidden)
        self.region = nn.Sequential(nn.Linear(hidden+4, hidden), nn.GELU(), nn.Linear(hidden, 1))
        self.global_net = nn.Sequential(nn.Linear(2*hidden+5+cfg.global_evidence_dim, hidden), nn.GELU())
        self.op = nn.Linear(hidden, 2)
        self.layer = nn.Linear(hidden, cfg.num_layers)
        for head in (self.op, self.layer, self.region[-1]):
            nn.init.orthogonal_(head.weight, gain=.01)
            nn.init.zeros_(head.bias)

    def forward(self, observation, actions=None, sample=True):
        spatial, context = observation["spatial"], observation["context"]
        features = self.encoder(spatial)
        if "roi_boxes" in observation:
            # The candidate index is part of the behavior action semantics.
            # Never rerun top-k in shuffled PPO minibatches: ties could change
            # which patch a stored region index refers to on another kernel.
            boxes = observation["roi_boxes"]
            height, width = spatial.shape[-2:]
            norm = boxes.new_tensor([height-1, width-1, height-1, width-1]).clamp_min(1)
            bounds = (boxes*norm).round().long()[..., None, None]
            yy = torch.arange(height, device=spatial.device).view(1, 1, height, 1)
            xx = torch.arange(width, device=spatial.device).view(1, 1, 1, width)
            masks = ((yy >= bounds[:, :, 0]) & (yy <= bounds[:, :, 2])
                     & (xx >= bounds[:, :, 1]) & (xx <= bounds[:, :, 3])).to(spatial.dtype)
        else:
            masks, boxes = build_candidate_masks(spatial[:, :1], spatial[:, 1:2], self.cfg.num_regions, self.cfg.roi_size)
        region = self.region(torch.cat([_masked_mean(features, masks), boxes], -1)).squeeze(-1)
        pooled = torch.cat([features.mean((-2, -1)), features.amax((-2, -1)), context], -1)
        global_features = self.global_net(pooled)
        logits = {"op": self.op(global_features), "region": region, "layer": self.layer(global_features)}
        distributions = {k: Categorical(logits=v) for k, v in logits.items()}
        if actions is None:
            actions = {k: d.sample() if sample else logits[k].argmax(-1) for k, d in distributions.items()}
        refine = (actions["op"] == 1).float()
        logprob = distributions["op"].log_prob(actions["op"])
        logprob = logprob+refine*(distributions["region"].log_prob(actions["region"])
                                 +distributions["layer"].log_prob(actions["layer"]))
        # Exact entropy of the 1 + K*L semantic-action distribution.
        entropy = distributions["op"].entropy()+distributions["op"].probs[:, 1]*(
            distributions["region"].entropy()+distributions["layer"].entropy())
        return dict(actions=actions, logprob=logprob, entropy=entropy, masks=masks, boxes=boxes, logits=logits)


class Critic(nn.Module):
    def __init__(self, cfg):
        super().__init__()
        hidden = cfg.hidden_dim
        self.encoder = encoder(7+cfg.num_layers+cfg.evidence_channels, hidden)
        self.value = nn.Sequential(nn.Linear(2*hidden+5+cfg.global_evidence_dim, hidden), nn.GELU(), nn.Linear(hidden, 1))
        # Zero initial baseline: the first update has no arbitrary signed offset.
        nn.init.zeros_(self.value[-1].weight)
        nn.init.zeros_(self.value[-1].bias)

    def forward(self, observation):
        features = self.encoder(observation["spatial"])
        pooled = torch.cat([features.mean((-2, -1)), features.amax((-2, -1)), observation["context"]], -1)
        return self.value(pooled).squeeze(-1)  # Linear, signed, unbounded V(s).


def return_targets(rewards, dones, valid, values, gamma=1., lam=1., use_value=True):
    """Complete finite-horizon episodes; horizon is terminal, NEVER bootstrapped.

    lambda=1 gives A=G-V_old exactly; critic targets are always full MC G.
    No averaging across different intermediate states or forced Base anchors.
    """
    returns, advantages = torch.zeros_like(rewards), torch.zeros_like(rewards)
    running, gae, next_value = [torch.zeros_like(rewards[:, 0]) for _ in range(3)]
    baseline = values if use_value else torch.zeros_like(values)
    for t in range(rewards.shape[1]-1, -1, -1):
        continuation = (~dones[:, t]).float()
        running = (rewards[:, t]+gamma*continuation*running)*valid[:, t]
        delta = rewards[:, t]+gamma*continuation*next_value-baseline[:, t]
        gae = (delta+gamma*lam*continuation*gae)*valid[:, t]
        returns[:, t], advantages[:, t] = running, gae
        next_value = baseline[:, t]*valid[:, t]
    return returns.detach(), advantages.detach()


class MARAPPOAgent(nn.Module):
    """Model-free Actor-Critic controller; frozen Refiner is the environment."""
    def __init__(self, cfg: MARAConfig, ppo: PPOConfig):
        super().__init__()
        if cfg.use_gain_gate or cfg.hard_gain_gate or not cfg.freeze_noop_state or cfg.force_first_refine:
            raise ValueError("PPO requires no gain veto, exact no-op and no forced first action")
        self.cfg, self.ppo = cfg, ppo
        self.transition = MARAAgent(cfg).requires_grad_(False).eval()
        self.actor, self.critic = Actor(cfg), Critic(cfg)
        if not ppo.use_value:
            self.critic.requires_grad_(False)

    def train(self, mode=True):
        super().train(mode)
        self.transition.eval()
        return self

    def initialize_refiner(self, state):
        # Strict loading prevents a zero/random Refiner being mistaken for a trained one.
        self.transition.load_state_dict(state, strict=True)

    def observe(self, raw, proposal, gate, logits, base_logits, global_evidence, step):
        bsz = raw.shape[0]
        remaining = raw.new_full((bsz, 1), (self.cfg.max_steps-step)/self.cfg.max_steps)
        if global_evidence is None:
            global_evidence = raw.new_zeros((bsz, self.cfg.global_evidence_dim))
        return dict(spatial=torch.cat([raw, proposal, gate], 1).detach(),
                    context=torch.cat([logits, base_logits, global_evidence, remaining], 1).detach())

    @torch.no_grad()
    def trajectory(self, inputs, sample=True, keep_observations=False):
        """GT-free transition execution. Return full maps for subsequent scoring."""
        if set(inputs)-set(INPUTS):
            raise ValueError("GT/unknown keys forbidden in policy inputs")
        validate_cache(inputs, self.cfg, allow_batch=True)
        cfg = self.cfg
        base_hr = inputs["base_prob"].detach()
        base = _resize_map(base_hr, cfg.map_size)
        layers = _resize_map(inputs["layer_maps"], cfg.map_size)
        evidence = inputs.get("evidence_maps")
        evidence = None if evidence is None else _resize_map(evidence, cfg.map_size)
        proposal, current, gate = base.clamp(1e-6, 1.).log(), base, torch.zeros_like(base[:, :1])
        logits = inputs["base_logits"].detach()
        active = torch.ones(len(base), dtype=torch.bool, device=base.device)
        steps, before_hr = [], base_hr
        for t in range(cfg.max_steps):
            raw = self.transition._make_state(current, base, layers, t, evidence)
            observation = self.observe(raw, proposal, gate, logits, inputs["base_logits"], inputs.get("global_evidence"), t)
            policy = self.actor(observation, sample=sample)
            value = self.critic(observation) if self.ppo.use_value else base.new_zeros(len(base))
            actions = policy["actions"]
            policy_out = dict(masks=policy["masks"], **{k+"_action": v for k, v in actions.items()})
            out = self.transition._refine(base, inputs["base_logits"], proposal, current, logits,
                                          gate, raw, layers, policy_out, active, False, False)
            after_hr, gate_hr = _compose_high_res_probability(base_hr, out["next_logits"], out["next_cumulative_gate"])
            done = (~out["next_active"]) | (t+1 == cfg.max_steps)
            step = dict(valid=active.clone(), done=done, actions=actions, old_logprob=policy["logprob"],
                        old_value=value, before_hr=before_hr, after_hr=after_hr,
                        before_logits=logits, after_logits=out["next_global_logits"],
                        execute=out["execute_weight"], p_stop=policy["logits"]["op"].softmax(-1)[:, 0],
                        box=policy["boxes"].gather(1, actions["region"][:, None, None].expand(-1, 1, 4))[:, 0],
                        pixel_change=(after_hr-before_hr).abs().flatten(1).amax(1),
                        global_change=(out["next_global_logits"]-logits).abs().amax(1))
            if keep_observations:
                observation["roi_boxes"] = policy["boxes"].detach()
                step["observation"] = observation
            steps.append(step)
            proposal, current, gate, logits, active = (out["next_logits"], out["next_prob"],
                out["next_cumulative_gate"], out["next_global_logits"], out["next_active"] & ~done)
            before_hr = after_hr
        return dict(steps=steps, final_prob=after_hr, final_logits=logits, gate_map=gate_hr)

    @torch.no_grad()
    def collect(self, inputs, mask, labels):
        count = self.ppo.trajectories
        repeated = {k: v.repeat_interleave(count, 0) for k, v in inputs.items() if v is not None}
        mask, labels = mask.repeat_interleave(count, 0), labels.repeat_interleave(count, 0)
        result = self.trajectory(repeated, sample=True, keep_observations=True)
        score_trajectory(result, mask, labels, self.cfg, self.ppo)
        steps = result["steps"]
        # Each stored row is its ACTUAL behavior observation; actions/logp/V/G/A
        # are detached and fixed for all minibatch passes, then discarded.
        batch = {k: torch.stack([s[k] for s in steps], 1).flatten(0, 1)
                 for k in ("valid", "old_logprob", "old_value", "return", "advantage")}
        batch["observation"] = {k: torch.stack([s["observation"][k] for s in steps], 1).flatten(0, 1)
                                for k in ("spatial", "context", "roi_boxes")}
        batch["actions"] = {k: torch.stack([s["actions"][k] for s in steps], 1).flatten(0, 1)
                            for k in ("op", "region", "layer")}
        valid = batch.pop("valid")
        for k in list(batch):
            batch[k] = {n: v[valid].detach() for n, v in batch[k].items()} if isinstance(batch[k], dict) else batch[k][valid].detach()
        summary = dict(trajectories=len(labels), decisions=int(valid.sum()),
                       return_mean=float(steps[0]["return"].mean()),
                       refine_mean=float(sum(s["execute"] for s in steps).mean()),
                       first_stop_fraction=float((steps[0]["actions"]["op"] == 0).float().mean()),
                       negative_refines=sum(int(((s["reward"] < 0) & (s["execute"] > 0)).sum()) for s in steps))
        return batch, summary

    @torch.no_grad()
    def infer(self, base_prob, base_logits, layer_maps=None, evidence_maps=None, global_evidence=None, sample=False):
        inputs = dict(base_prob=base_prob, base_logits=base_logits, layer_maps=layer_maps,
                      evidence_maps=evidence_maps, global_evidence=global_evidence)
        result = self.trajectory(inputs, sample=sample)
        counts = sum(s["execute"] for s in result["steps"])
        gate, final = result["gate_map"], result["final_prob"]
        change = (gate > 1e-6).float()
        # A zero spatial gate must be an exact identity at original resolution.
        identity = (final-base_prob).abs()*(gate == 0)
        return dict(final_prob=final, final_logits=result["final_logits"], gate_map=gate,
                    refine_steps=counts, refine_attempts=counts, rejected_steps=torch.zeros_like(counts),
                    gate_roi_mean=(gate*change).sum((1, 2, 3))/change.sum((1, 2, 3)).clamp_min(1),
                    changed_ratio=change.mean((1, 2, 3)), identity_error_mean=identity.mean((1, 2, 3)),
                    identity_error_max=identity.flatten(1).amax(1))


@torch.no_grad()
def score_trajectory(result, mask, labels, cfg, ppo):
    """GT enters AFTER execution, only to construct HR rewards/targets."""
    steps = result["steps"]
    for step in steps:
        before = quality_score(step["before_hr"], step["before_logits"], mask, labels, cfg)
        after = quality_score(step["after_hr"], step["after_logits"], mask, labels, cfg)
        step["quality_before"], step["quality_after"] = before, after
        step["reward"] = (after-before-(cfg.step_cost+cfg.refine_cost)*step["execute"])*step["valid"]
    stack = lambda key: torch.stack([s[key] for s in steps], 1)
    returns, advantages = return_targets(stack("reward"), stack("done"), stack("valid"), stack("old_value"),
                                         ppo.gamma, ppo.gae_lambda, ppo.use_value)
    for t, step in enumerate(steps):
        step["return"], step["advantage"] = returns[:, t], advantages[:, t]


def optimizers(agent):
    actor = torch.optim.Adam(agent.actor.parameters(), lr=agent.ppo.actor_lr, eps=1e-5)
    critic = torch.optim.Adam(agent.critic.parameters(), lr=agent.ppo.critic_lr, eps=1e-5) if agent.ppo.use_value else None
    return actor, critic


def update(agent, batch, actor_optimizer, critic_optimizer, entropy_coef=None):
    """Finite PPO passes over one fresh batch. No environment replay/backprop."""
    cfg, rows = agent.ppo, []
    count = len(batch["return"])
    entropy_coef = cfg.entropy_coef if entropy_coef is None else entropy_coef
    for _ in range(cfg.update_epochs):
        order = torch.randperm(count, device=batch["return"].device)
        for ids in order.split(cfg.minibatch_size):
            observation = {k: v[ids] for k, v in batch["observation"].items()}
            actions = {k: v[ids] for k, v in batch["actions"].items()}
            policy = agent.actor(observation, actions=actions)
            logratio = policy["logprob"]-batch["old_logprob"][ids]
            ratio, advantage = logratio.exp(), batch["advantage"][ids]
            policy_loss = -torch.minimum(ratio*advantage, ratio.clamp(1-cfg.clip_eps, 1+cfg.clip_eps)*advantage).mean()
            entropy = policy["entropy"].mean()
            actor_loss = policy_loss-entropy_coef*entropy
            value_loss = actor_loss.new_zeros(())
            if cfg.use_value:
                prediction = agent.critic(observation)
                value_loss = .5*(prediction-batch["return"][ids]).square().mean()
            loss = actor_loss+cfg.value_coef*value_loss
            if not torch.isfinite(loss):
                raise ValueError("Nonfinite PPO loss; refusing a partial optimizer update")
            actor_optimizer.zero_grad(set_to_none=True)
            if critic_optimizer is not None:
                critic_optimizer.zero_grad(set_to_none=True)
            loss.backward()
            grad_actor = nn.utils.clip_grad_norm_(agent.actor.parameters(), cfg.grad_clip, error_if_nonfinite=True)
            if critic_optimizer is not None:
                nn.utils.clip_grad_norm_(agent.critic.parameters(), cfg.grad_clip, error_if_nonfinite=True)
            actor_optimizer.step()
            if critic_optimizer is not None:
                critic_optimizer.step()
            rows.append(dict(weight=len(ids), loss=float(loss.detach()), policy_loss=float(policy_loss.detach()),
                             value_loss=float(value_loss.detach()), entropy=float(entropy.detach()),
                             approx_kl=float(((ratio-1)-logratio).mean().detach()),
                             clip_fraction=float(((ratio-1).abs() > cfg.clip_eps).float().mean()),
                             actor_grad_norm=float(grad_actor)))
    weight = sum(r["weight"] for r in rows)
    metrics = {k: sum(r[k]*r["weight"] for r in rows)/weight for k in rows[0] if k != "weight"}
    variance = batch["return"].var(unbiased=False)
    error_var = (batch["return"]-batch["old_value"]).var(unbiased=False)
    metrics.update(optimizer_steps=len(rows), old_value_mean=float(batch["old_value"].mean()),
                   advantage_mean=float(batch["advantage"].mean()),
                   advantage_std=float(batch["advantage"].std(unbiased=False)), return_std=float(variance.sqrt()),
                   explained_variance=float(1-error_var/variance) if variance > 1e-12 else 0.,
                   entropy_coef=entropy_coef)
    return metrics


def agent_from_payload(payload):
    if payload.get("mara_algorithm") != PROTOCOL:
        raise ValueError("Not a MARA PPO checkpoint")
    agent = MARAPPOAgent(MARAConfig(**payload["mara_config"]), PPOConfig(**payload["ppo_config"]))
    agent.load_state_dict(payload["mara_ppo_agent"], strict=True)
    return agent
